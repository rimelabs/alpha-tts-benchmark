def _all_combos() -> list[dict]:
    rows: list[dict] = []
    for domain, frames in _DOMAINS:
        for frame, slots in frames:
            for slot in slots:
                text = frame if slot is None else frame.format(x=slot)
                rows.append(sentence(CATEGORY, domain, text, NOTE, template=frame))
    for line in _STANDALONE:
        rows.append(sentence(CATEGORY, "standalone", line, NOTE, template=line))
    texts = [r["text"] for r in rows]
    dupes = {t for t in texts if texts.count(t) > 1}
    assert not dupes, f"duplicate authored sentences: {dupes}"
    return rows


def generate(rng: random.Random, n: int) -> list[dict]:
    combos = _all_combos()
    if n > len(combos):
        raise ValueError(f"requested {n} sentences but only {len(combos)} valid combinations exist")
    picked = rng.sample(combos, n)
    picked.sort(key=lambda r: (r["subcategory"], r["text"]))
    return picked
